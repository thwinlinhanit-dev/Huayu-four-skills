// Reverse map for traditional to simplified
const TRAD_TO_SIMP: Record<string, string> = Object.entries(SIMP_TO_TRAD).reduce(
  (acc, [simp, trad]) => {
    acc[trad] = simp;
    return acc;
  },
  {} as Record<string, string>
);

export type ScriptMode = 'simplified' | 'traditional';

/**
 * Converts a string to either Simplified or Traditional Chinese.
 */
export function convertScript(text: string, targetMode: ScriptMode): string {
  if (!text) return '';
  const map = targetMode === 'traditional' ? SIMP_TO_TRAD : TRAD_TO_SIMP;
  return text
    .split('')
    .map((char) => map[char] || char)
    .join('');
}
