// Offline stroke-vector pack covering every character in CHARACTERS_DATABASE,
// so the writing canvas, stroke animator and dictation work with no network.
// Regenerate with: bun scripts/fetchStrokes.ts
export const PRECACHED_STROKES: Record<string, HanziCharData> = {
  ...CORE_STROKES,
  ...EXPANDED_STROKES,
};

const dynamicCache = new Map<string, HanziCharData>();

export async function getCharacterStrokeData(char: string): Promise<HanziCharData | null> {
  if (PRECACHED_STROKES[char]) {
    return PRECACHED_STROKES[char];
  }
  if (dynamicCache.has(char)) {
    return dynamicCache.get(char)!;
  }
  try {
    const encoded = encodeURIComponent(char);
    const res = await fetch(`https://cdn.jsdelivr.net/npm/hanzi-writer-data@2.0/${encoded}.json`);
    if (!res.ok) return null;
    const data: HanziCharData = await res.json();
    dynamicCache.set(char, data);
    return data;
  } catch (err) {
    console.warn('Could not load stroke data for character:', char, err);
    return null;
  }
}
